#!/usr/bin/env python3
"""Generate explicit Codable snapshots; no reflection or runtime dependency."""
from pathlib import Path
import re

ROOT = Path(__file__).resolve().parents[1]
source = (ROOT / 'Fitness/Core/Models.swift').read_text(encoding='utf-8')
records = []
for match in re.finditer(r'@Model final class (\w+) \{(.*?)\n        init\(', source, re.S):
    name, fields = match.group(1), []
    for field in re.finditer(r'\bvar (\w+): ([\w\[\]?]+)', match.group(2)):
        fields.append((field.group(1), field.group(2)))
    records.append((name, fields))
lines = ['// Generated by scripts/generate_backup_records.py. Commit the generated source.', 'import Foundation', 'import SwiftData', '']
for name, fields in records:
    lines.append(f'struct {name}Record: Codable {{')
    lines.extend(f'    var {field}: {kind}' for field, kind in fields)
    lines.append(f'    init(_ model: {name}) {{')
    lines.extend(f'        {field} = model.{field}' for field, _ in fields)
    lines.extend(['    }', f'    func apply(to model: {name}) {{'])
    lines.extend(f'        model.{field} = {field}' for field, _ in fields)
    lines.extend(['    }', f'    func makeModel() -> {name} {{', f'        let model = {name}()', '        apply(to: model)', '        return model', '    }', '}', ''])
target = ROOT / 'Fitness/Core/BackupRecords.swift'
target.parent.mkdir(parents=True, exist_ok=True)
target.write_text('\n'.join(lines), encoding='utf-8')
print(f'Generated {len(records)} record types.')
